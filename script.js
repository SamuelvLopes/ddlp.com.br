const buttons = document.querySelectorAll("[data-lang]");
const translatable = document.querySelectorAll("[data-i18n]");
const ariaTranslatable = document.querySelectorAll("[data-i18n-aria-label]");
const description = document.querySelector('meta[name="description"]');
const ogDescription = document.querySelector('meta[property="og:description"]');

function detectLanguage() {
  const saved = getSavedLanguage();
  if (saved && translations[saved]) return saved;

  const browserLanguage = navigator.language || "pt-BR";
  if (browserLanguage.startsWith("es")) return "es";
  if (browserLanguage.startsWith("en")) return "en";
  return "pt-BR";
}

function getSavedLanguage() {
  try {
    return window.localStorage.getItem("ddlp-language");
  } catch {
    return null;
  }
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem("ddlp-language", language);
  } catch {
    // The selected language still applies for the current page view.
  }
}

function setLanguage(language) {
  const copy = translations[language];
  document.documentElement.lang = language;

  translatable.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) node.textContent = copy[key];
  });

  ariaTranslatable.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    if (copy[key]) node.setAttribute("aria-label", copy[key]);
  });

  buttons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });

  document.title = language === "pt-BR" ? "DDLP" : `DDLP - ${copy.kicker}`;
  description?.setAttribute("content", copy.description);
  ogDescription?.setAttribute("content", copy.tagline);
  saveLanguage(language);
}

buttons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

setLanguage(detectLanguage());
